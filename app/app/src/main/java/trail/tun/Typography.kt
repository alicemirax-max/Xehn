package trail.tun

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.LineHeightStyle
import androidx.compose.ui.unit.sp

/**
 * Type scale.
 *
 * Two adjustments against the Material defaults, both for legibility on a phone
 * held at arm's length in bad light:
 *
 *  - Body sizes get slightly more leading, because the status cards hold dense
 *    numbers and addresses that run together at default spacing.
 *  - Labels move to a tighter weight but larger size, so "Received / Sent /
 *    Uptime" reads at a glance instead of needing a squint.
 */
